"""
Pluggable LLM interface supporting streaming chat and post-call data extraction.
Uses Groq OpenAI-compatible API by default with configurable model and low temperature.
"""
from __future__ import annotations

import json
import os
from typing import Any, AsyncIterator, Dict, List, Optional

import httpx

GROQ_BASE_URL = "https://api.groq.com/openai/v1"
DEFAULT_MODEL = "qwen/qwen3.8-27b"


class LLMClient:
    """Client for streaming dialogue generation and post-conversation extraction."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        base_url: Optional[str] = None,
    ) -> None:
        """Initialize LLM client with credentials, model name, and endpoint."""
        self._api_key = api_key or os.getenv("GROQ_API_KEY", "")
        self._model = model or os.getenv("LLM_MODEL", DEFAULT_MODEL)
        self._base_url = base_url or GROQ_BASE_URL

        if not self._api_key:
            raise ValueError("GROQ_API_KEY is not set or empty")

    async def stream_chat(
        self,
        messages: List[Dict[str, str]],
        temperature: float = 0.2,
        max_tokens: int = 256,
    ) -> AsyncIterator[str]:
        """
        Stream tokens from LLM completion using server-sent events.

        Yields string text deltas as generated by the model.
        """
        headers = {
            "Authorization": f"Bearer {self._api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self._model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
            "stream": True,
        }

        async with httpx.AsyncClient(timeout=20.0) as client:
            async with client.stream(
                "POST", f"{self._base_url}/chat/completions", headers=headers, json=payload
            ) as resp:
                resp.raise_for_status()
                async for line in resp.aiter_lines():
                    if not line.startswith("data:"):
                        continue
                    raw_data = line[5:].strip()
                    if raw_data == "[DONE]":
                        break
                    try:
                        chunk = json.loads(raw_data)
                    except json.JSONDecodeError:
                        continue

                    choices = chunk.get("choices", [])
                    if choices:
                        delta = choices[0].get("delta", {})
                        content = delta.get("content", "")
                        if content:
                            yield content

    async def extract_session_data(
        self,
        transcript: List[Dict[str, str]],
        info_to_collect: List[Dict[str, Any]],
        success_condition: str,
    ) -> Dict[str, Any]:
        """
        Extract structured outcomes and collected entity values from conversation transcript.

        Returns JSON dict matching schema with outcome, sentiment, summary, and fields.
        """
        conversation_text = "\n".join(
            f"{m.get('role', 'user').capitalize()}: {m.get('content', '')}"
            for m in transcript
        )

        extraction_system_prompt = (
            "You are a structured data extractor for voice customer service calls.\n"
            "Analyze the conversation transcript and return ONLY a valid JSON object with these exact keys:\n"
            "- fields_collected: dict mapping field names from the requested fields list to extracted values (or null if not provided)\n"
            "- outcome: one of ['agreed', 'declined', 'callback_requested', 'wrong_number', 'unanswered']\n"
            "- call_summary: 2-3 concise sentences in English explaining what transpired\n"
            "- user_sentiment: one of ['positive', 'neutral', 'negative']\n"
            "- follow_up_needed: boolean\n"
            "- language_used: primary language observed (e.g. 'en-IN', 'hi-IN', 'te-IN')\n"
            "- confidence: float between 0.0 and 1.0\n"
            "Output strictly valid JSON and nothing else. No markdown fences."
        )

        user_content = (
            f"Requested fields to collect: {json.dumps(info_to_collect)}\n"
            f"Success criteria: {success_condition}\n\n"
            f"Conversation Transcript:\n{conversation_text}"
        )

        messages = [
            {"role": "system", "content": extraction_system_prompt},
            {"role": "user", "content": user_content},
        ]

        headers = {
            "Authorization": f"Bearer {self._api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self._model,
            "messages": messages,
            "temperature": 0.1,
            "max_tokens": 512,
            "stream": False,
        }

        async with httpx.AsyncClient(timeout=25.0) as client:
            resp = await client.post(
                f"{self._base_url}/chat/completions", headers=headers, json=payload
            )
            resp.raise_for_status()
            content = resp.json()["choices"][0]["message"]["content"].strip()
            if content.startswith("```"):
                content = content.strip("`").replace("json\n", "", 1).strip()
            try:
                return json.loads(content)
            except json.JSONDecodeError:
                return {
                    "fields_collected": {},
                    "outcome": "unanswered",
                    "call_summary": content[:200],
                    "user_sentiment": "neutral",
                    "follow_up_needed": True,
                    "language_used": "unknown",
                    "confidence": 0.5,
                }
